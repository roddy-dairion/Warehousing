#!/usr/bin/env node
/**
 * Build-time settings for the mobile app in CI (Codemagic). Run from the frontend folder.
 *
 *   node scripts/mobile-ci.mjs env           Writes projects/mobile/src/environments/environment.ts with API_BASE_URL.
 *                                            HTTPS is required unless CAP_DEV=1 (test builds talking to a PC on the local network).
 *   node scripts/mobile-ci.mjs ios-version   Sets the iOS version (APP_VERSION, e.g. 1.0.0) and build number (BUILD_NUMBER)
 *                                            in the Xcode project. Android gets them as Gradle properties instead.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const command = process.argv[2];

function fail(message) {
  console.error(`mobile-ci: ${message}`);
  process.exit(1);
}

if (command === 'env') {
  const url = (process.env.API_BASE_URL ?? '').trim().replace(/\/+$/, '');
  if (!url) fail('API_BASE_URL is not set (e.g. https://api.example.com/api/v1).');
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    fail(`API_BASE_URL is not a valid URL: ${url}`);
  }
  if (parsed.protocol !== 'https:' && process.env.CAP_DEV !== '1') fail('API_BASE_URL must use https:// (set CAP_DEV=1 only for test builds on a local network).');
  if (!parsed.pathname.endsWith('/api/v1')) console.warn(`mobile-ci: warning, API_BASE_URL usually ends with /api/v1 (got ${url}).`);
  const file = 'projects/mobile/src/environments/environment.ts';
  writeFileSync(file, `// Generated by scripts/mobile-ci.mjs for a CI build. Do not commit.\nexport const environment = {\n  production: true,\n  apiBaseUrl: ${JSON.stringify(url)},\n};\n`);
  console.log(`mobile-ci: ${file} -> ${url}`);
} else if (command === 'ios-version') {
  const version = (process.env.APP_VERSION ?? '1.0.0').trim();
  const build = (process.env.BUILD_NUMBER ?? '1').trim();
  if (!/^\d+(\.\d+){0,2}$/.test(version)) fail(`APP_VERSION must look like 1.0.0 (got ${version}).`);
  if (!/^\d+$/.test(build)) fail(`BUILD_NUMBER must be a whole number (got ${build}).`);
  const file = 'projects/mobile/ios/App/App.xcodeproj/project.pbxproj';
  const text = readFileSync(file, 'utf8')
    .replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${version};`)
    .replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${build};`);
  writeFileSync(file, text);
  console.log(`mobile-ci: iOS version ${version} (${build})`);
} else {
  fail('usage: node scripts/mobile-ci.mjs <env|ios-version>');
}
