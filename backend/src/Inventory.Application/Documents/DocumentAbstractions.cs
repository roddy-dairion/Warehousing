namespace Inventory.Application.Documents;

/// <summary>Liquid template engine (implemented with Fluid). Templates only see the data model passed to them.</summary>
public interface ITemplateEngine
{
    /// <summary>Returns null when the template parses, otherwise the error message (with line/column).</summary>
    string? Validate(string template);

    /// <summary>Renders the template. With <paramref name="htmlEncode"/> every output value is HTML-encoded (documents); without it, plain text (email).</summary>
    Task<string> RenderAsync(string template, IReadOnlyDictionary<string, object?> model, bool htmlEncode, string timeZone, CancellationToken cancellationToken);
}

/// <summary>Turns HTML into a PDF (A4). Scripts and network access are disabled while rendering.</summary>
public interface IPdfRenderer
{
    Task<byte[]> RenderAsync(string html, CancellationToken cancellationToken);
}

/// <summary>Sends one email; implemented with SMTP (MailKit) or a pickup folder in development.</summary>
public interface IEmailSender
{
    Task SendAsync(OutgoingEmail email, CancellationToken cancellationToken);
}

public sealed record EmailAttachment(string FileName, string ContentType, byte[] Content);

public sealed record OutgoingEmail(IReadOnlyList<string> To, IReadOnlyList<string> Bcc, string Subject, string TextBody, IReadOnlyList<EmailAttachment> Attachments);

public sealed class DocumentOptions
{
    public const string Section = "Documents";

    /// <summary>Attempts before a document is marked failed (it can still be regenerated by hand).</summary>
    public int MaxAttempts { get; set; } = 5;
}
