using System.Security.Cryptography;
using Inventory.Application.Common;
using Inventory.Domain.Documents;
using Inventory.Domain.Files;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Inventory.Application.Documents;

/// <summary>
/// Generates dispatch PDFs from the current template version and queues the delivery-note email. Generation runs after
/// the business transaction commits; if it fails the document stays pending and the background worker retries.
/// </summary>
public sealed partial class DocumentService(
    IApplicationDbContext db,
    DocumentModelBuilder models,
    ITemplateEngine templates,
    IPdfRenderer pdf,
    IFileStorage files,
    IWarehouseAccess access,
    ICurrentUser user,
    TimeProvider clock,
    IAuditWriter audit,
    IOptions<DocumentOptions> options,
    ILogger<DocumentService> logger)
{
    public const string FileOwner = "dispatch_document";
    public const string EmailRelatedType = "dispatch";

    /// <summary>Generates now; never throws (failures are recorded on the document and retried later).</summary>
    public async Task<bool> TryGenerateAsync(Guid documentId, CancellationToken cancellationToken)
    {
        try
        {
            return await GenerateAsync(documentId, cancellationToken);
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            LogGenerationFailed(logger, e, documentId);
            return false;
        }
    }

    /// <summary>Renders the PDF for a pending document. Returns false if it was not pending (or failed, see LastError).</summary>
    public async Task<bool> GenerateAsync(Guid documentId, CancellationToken cancellationToken)
    {
        var doc = await db.DispatchDocuments.AsTracking().SingleOrDefaultAsync(x => x.Id == documentId, cancellationToken);
        if (doc is null || doc.Status != DocumentStatus.Pending) return false;

        var company = await CompanyAsync(cancellationToken);
        var template = await db.DocumentTemplates.AsNoTracking().SingleAsync(t => t.Type == doc.Type && t.IsCurrent, cancellationToken);
        byte[] bytes;
        try
        {
            var model = await models.BuildAsync(doc.DispatchId, doc.Type, company, cancellationToken);
            var html = await templates.RenderAsync(template.Html, model, htmlEncode: true, company.TimeZone, cancellationToken);
            bytes = await pdf.RenderAsync(html, cancellationToken);
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            doc.MarkFailed(e.Message, options.Value.MaxAttempts);
            await db.SaveChangesAsync(CancellationToken.None);
            LogGenerationFailed(logger, e, documentId);
            return false;
        }

        var number = await db.Dispatches.Where(d => d.Id == doc.DispatchId).Select(d => d.Number).SingleAsync(cancellationToken);
        using var stream = new MemoryStream(bytes);
        var key = await files.SaveAsync(stream, cancellationToken);
        var fileName = $"{(doc.Type == DocumentType.DeliveryNote ? "delivery-note" : "packing-slip")}-{number}.pdf";
        var stored = StoredFile.Create(fileName, "application/pdf", bytes.Length, key, Convert.ToHexStringLower(SHA256.HashData(bytes)), FileOwner, doc.DispatchId,
            clock.GetUtcNow(), doc.RequestedBy);
        db.StoredFiles.Add(stored);
        doc.MarkGenerated(stored.Id, template.Id, clock.GetUtcNow());
        if (doc.EmailToCustomer) await QueueDeliveryEmailAsync(doc, null, cancellationToken);
        try
        {
            await db.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateConcurrencyException)
        {
            // Generated by someone else (worker and request at the same time): keep theirs.
            foreach (var entry in db.ChangeTracker.Entries().Where(e => e.State != EntityState.Unchanged).ToList()) entry.State = EntityState.Detached;
            await files.DeleteAsync(key, CancellationToken.None);
            return false;
        }
        return true;
    }

    /// <summary>
    /// Queues the delivery-note email to <paramref name="to"/> or, by default, the customer's email (plus the configured copy).
    /// Without a customer email nothing is queued and the reason is audited; the PDF stays available for download.
    /// </summary>
    public async Task QueueDeliveryEmailAsync(DispatchDocument doc, string? to, CancellationToken cancellationToken)
    {
        var d = await db.Dispatches.AsNoTracking().SingleAsync(x => x.Id == doc.DispatchId, cancellationToken);
        var recipient = string.IsNullOrWhiteSpace(to)
            ? await db.Customers.Where(c => c.Id == d.CustomerId).Select(c => c.Email).SingleAsync(cancellationToken)
            : to.Trim();
        if (string.IsNullOrWhiteSpace(recipient))
        {
            audit.Add("delivery_note.no_recipient", "dispatch", d.Id.ToString(), d.WarehouseId, new { d.Number });
            return;
        }
        if (!System.Net.Mail.MailAddress.TryCreate(recipient, out _))
        {
            throw new Domain.Common.DomainRuleException("email.invalid", $"{recipient} is not a valid email address.");
        }

        var company = await CompanyAsync(cancellationToken);
        var model = await models.BuildAsync(d.Id, DocumentType.DeliveryNote, company, cancellationToken);
        var subject = await templates.RenderAsync(company.DeliveryEmailSubject, model, htmlEncode: false, company.TimeZone, cancellationToken);
        var body = await templates.RenderAsync(company.DeliveryEmailBody, model, htmlEncode: false, company.TimeZone, cancellationToken);
        var message = EmailMessage.Create(recipient, company.DeliveryEmailBcc, subject.Trim(), body, [doc.FileId!.Value], EmailRelatedType, d.Id, clock.GetUtcNow());
        db.EmailMessages.Add(message);
        audit.Add("delivery_note.email_queued", "dispatch", d.Id.ToString(), d.WarehouseId, new { d.Number, to = recipient });
    }

    /// <summary>Queues a fresh document (e.g. after a template change) and tries to generate it now.</summary>
    public async Task<Guid> RegenerateAsync(Guid dispatchId, DocumentType type, CancellationToken cancellationToken)
    {
        var d = await db.Dispatches.AsNoTracking().SingleOrDefaultAsync(x => x.Id == dispatchId, cancellationToken) ?? throw new NotFoundException("Dispatch not found.");
        await access.EnsureCanAccessAsync(d.WarehouseId, cancellationToken);
        var allowed = type == DocumentType.PackingSlip
            ? d.Status is Domain.Dispatches.DispatchStatus.Dispatched or Domain.Dispatches.DispatchStatus.Delivered
            : d.Status == Domain.Dispatches.DispatchStatus.Delivered;
        if (!allowed)
        {
            throw new Domain.Common.DomainRuleException("document.not_available",
                type == DocumentType.PackingSlip ? "The packing slip is produced once the dispatch has shipped." : "The delivery note is produced once the delivery is recorded.", isConflict: true);
        }
        var doc = DispatchDocument.Request(dispatchId, type, emailToCustomer: false, user.IdOrNull, clock.GetUtcNow());
        db.DispatchDocuments.Add(doc);
        audit.Add("document.regenerate", "dispatch", dispatchId.ToString(), d.WarehouseId, new { d.Number, type = type.ToString() });
        await db.SaveChangesAsync(cancellationToken);
        await TryGenerateAsync(doc.Id, cancellationToken);
        return doc.Id;
    }

    public async Task<(Stream Content, string FileName)> OpenAsync(Guid dispatchId, Guid documentId, CancellationToken cancellationToken)
    {
        var d = await db.Dispatches.AsNoTracking().SingleOrDefaultAsync(x => x.Id == dispatchId, cancellationToken) ?? throw new NotFoundException("Dispatch not found.");
        await access.EnsureCanAccessAsync(d.WarehouseId, cancellationToken);
        var file = await (from doc in db.DispatchDocuments.AsNoTracking()
                          where doc.Id == documentId && doc.DispatchId == dispatchId && doc.Status == DocumentStatus.Generated
                          join f in db.StoredFiles on doc.FileId equals f.Id
                          select f).SingleOrDefaultAsync(cancellationToken) ?? throw new NotFoundException("Document not found.");
        var stream = await files.OpenReadAsync(file.StorageKey, cancellationToken) ?? throw new NotFoundException("Document file is missing.");
        return (stream, file.FileName);
    }

    internal async Task<CompanyProfile> CompanyAsync(CancellationToken cancellationToken) =>
        await db.CompanyProfiles.AsNoTracking().OrderBy(c => c.CreatedAt).FirstOrDefaultAsync(cancellationToken)
        ?? CompanyProfile.Create("Company");

    [LoggerMessage(Level = LogLevel.Warning, Message = "Document {DocumentId} could not be generated")]
    private static partial void LogGenerationFailed(ILogger logger, Exception e, Guid documentId);
}
